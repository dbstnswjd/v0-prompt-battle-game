export function generateRandomTopic(): string {
  const targetKeys = Object.keys(targetTopics)
  const target = targetKeys[Math.floor(Math.random() * targetKeys.length)]
  const combinations = targetTopics[target]
  const combination = combinations[Math.floor(Math.random() * combinations.length)]
  return `${target}을(를) 위한 / ${combination}`
}

export function getRandomDisplayTopics(count: number): string[] {
  const topics: string[] = []
  for (let i = 0; i < count; i++) {
    topics.push(generateRandomTopic())
  }
  return topics
}
